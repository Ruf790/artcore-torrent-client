def set_lang(lang: str) -> None:
    global _lang
    _lang = "en" if lang == "en" else "ru"


def t(key: str, *args) -> str:
    pair = STRINGS.get(key)
    s = (pair[0] if _lang == "ru" else pair[1]) if pair else key
    for i, a in enumerate(args):
        s = s.replace("{" + str(i) + "}", str(a))
    return s
